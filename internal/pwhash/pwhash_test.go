// SHA-crypt vectors generated with an independent implementation:
// `openssl passwd -5 -salt <salt> <password>` (OpenSSL 3).
func TestShaCrypt256AgainstOpenSSL(t *testing.T) {
	cases := []struct{ salt, password, want string }{
		{"abcdefghijklmnop", "a", "DPoS.d1vEHDatG9aGvI6mut5WS6yqh2q9mihBYl8JQ/"},
		{"abcdefghijklmnop", "hello world", "t0t34YabPKedPsoVIpJ3/gkPGyP7pioHdx/9BXMp.K4"},
		{"abcdefghijklmnop", "umDNGPl6N-JiorUfr9q4CsXCpmElUrtKZ2uOnp4T8RM", "MEZh/Xa6/yN16nxgwlmcklQmltncnKNeGnut2H.0kY5"},
		{"abcdefghijklmnop", strings.Repeat("x", 70), "9Hb3FAWHMjTRmtGxp5A6xgyNw0NwnVFXs5ShXabRso2"},
		{"saltsalt", "a", "Mtm6KOxb.PwaKES1sp80SDYOu1T0RdwsBVakhLiqA64"},
		{"saltsalt", "hello world", "iCSto/1y3LK1GxFWJB6bg2L4y8RyFskzzyTdhOwyBe3"},
		{"saltsalt", "umDNGPl6N-JiorUfr9q4CsXCpmElUrtKZ2uOnp4T8RM", "1dYCIaputsE.WXK44zEkNwdDyIUEECKB4sndxH7DLT4"},
		{"saltsalt", strings.Repeat("x", 70), "fSdtAAr549Wx1h7lL66XTpgqF.cls5UHCOgn4sOxZf6"},
	}
	for _, c := range cases {
		if got := shaCrypt256([]byte(c.password), []byte(c.salt), 5000); got != c.want {
			t.Errorf("salt %q password %q: got %s want %s", c.salt, c.password, got, c.want)
		}
	}
}

// A hash generated by a real MySQL 8.4 server for the password "second"
// (CREATE USER ... IDENTIFIED BY 'second'; SELECT HEX(authentication_string)).
// Note that MySQL's own salts contain control characters.
const mysqlServerHashHex = "244124303035246D4F2B3E6E2C481A504F334E20412A7E321C0148707A5644774B584A757154562F424263705467365574593956716B684D47544437634D33393553514B3241"

func TestMySQLMatchesServerHash(t *testing.T) {
	raw, err := hex.DecodeString(mysqlServerHashHex)
	if err != nil {
		t.Fatal(err)
	}
	if !MySQLMatches(string(raw), "second") {
		t.Fatal("hash produced by MySQL not recognized")
	}
	if MySQLMatches(string(raw), "secone") {
		t.Fatal("wrong password matched")
	}
}

func TestMySQLRoundTrip(t *testing.T) {
	rnd := make([]byte, 32)
	for i := range rnd {
		rnd[i] = byte(i * 37)
	}
	salt, err := MySQLSalt(rnd)
	if err != nil {
		t.Fatal(err)
	}
	h, err := MySQL("pw", salt)
	if err != nil {
		t.Fatal(err)
	}
	if len(h) != 70 || !strings.HasPrefix(h, "$A$005$") {
		t.Fatalf("bad framing: %q", h)
	}
	if !MySQLMatches(h, "pw") || MySQLMatches(h, "pW") {
		t.Fatal("MySQLMatches round trip failed")
	}
	if MySQLHex("$A") != "0x2441" {
		t.Fatal("MySQLHex")
	}
	for _, bad := range [][]byte{[]byte("short"), append([]byte("$"), make([]byte, 19)...)} {
		if _, err := MySQL("pw", bad); err == nil {
			t.Errorf("salt %q accepted", bad)
		}
	}
	if MySQLMatches("$A$00A$"+strings.Repeat("a", 63), "pw") {
		t.Error("foreign round count matched")
	}
}

// Expected value computed by scripts/derivation_vectors.py, which uses
// Python's hashlib (an independent PBKDF2/HMAC implementation).
func TestSCRAMVector(t *testing.T) {
	salt, _ := hex.DecodeString("abf9ab9a389f481fee4908dd172c9ccc")
	got, err := SCRAM("lRG6msAkg88kIIjJU-N6yWZ6wzx1gQj62GYG71hcgjE", salt)
	if err != nil {
		t.Fatal(err)
	}
	want := "SCRAM-SHA-256$4096:q/mrmjifSB/uSQjdFyyczA==$1vO+SFZOWRWMJtkvT14UZD23M4IOBqVfMP6JjpxyVnA=:LKeE/8nXPt7v7OoC/qRpjmb66Fd0fA5wclO1IK9ZOII="
	if got != want {
		t.Fatalf("got  %s\nwant %s", got, want)
	}
	if _, err := SCRAM("x", make([]byte, 15)); err == nil {
		t.Error("short salt accepted")
	}
}

